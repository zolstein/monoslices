func TestGeneratePackageAggregatesDeterministically(t *testing.T) {
	dir := genPackageFiles(t, map[string]string{
		"a.go": `package fixture

type A int
func compareA(left, right A) int { return int(left-right) }
//monoslices:generate name=As cmp=compareA ops=binary-search,compare
`,
		"b.go": `package fixture

type B int
func compareB(left, right B) int { return int(left-right) }
//monoslices:generate name=Bs cmp=compareB ops=compare
`,
	})
	loaded, err := loadpkg.LoadPackage(context.Background(), dir, config.CLIConfig{})
	if err != nil {
		t.Fatal(err)
	}
	plan, err := model.BuildPackage(loaded)
	if err != nil {
		t.Fatal(err)
	}
	first, err := GeneratePackage(plan)
	if err != nil {
		t.Fatal(err)
	}
	second, err := GeneratePackage(plan)
	if err != nil {
		t.Fatal(err)
	}
	if string(first) != string(second) {
		t.Fatal("repeated aggregate generation was not deterministic")
	}
	for _, want := range []string{"Code generated by monoslices. DO NOT EDIT.", "monoslices: a.go", "monoslices: b.go", "func AsCompare", "func AsBinarySearch", "func BsCompare"} {
		if !strings.Contains(string(first), want) {
			t.Errorf("aggregate source lacks %q", want)
		}
	}
	if strings.Count(string(first), "Code generated by monoslices. DO NOT EDIT.") != 1 {
		t.Fatal("ownership marker repeated")
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "generated.go", first, parser.ParseComments); err != nil {
		t.Fatalf("generated source does not parse: %v", err)
	}
}

func TestGenerateByrefMinMaxKeepsLiveBestElement(t *testing.T) {
	dir := genPackageFiles(t, map[string]string{
		"items.go": `package fixture

type Item struct { Key, Tag int }
func first(a *Item, b Item) int { return a.Key - b.Key }
func second(a Item, b *Item) int { return a.Key - b.Key }
func best(a, b *Item) int { return a.Key - b.Key }
//monoslices:generate name=First cmp=first byref=first ops=min,max
//monoslices:generate name=Second cmp=second byref=second ops=min,max
//monoslices:generate name=Both cmp=best byref=true ops=min,max
`,
		"items_test.go": `package fixture
import "testing"
func TestMinMax(t *testing.T) {
  for _, tc := range []struct { name string; min, max func([]Item) Item }{
    {"first", FirstMin, FirstMax}, {"second", SecondMin, SecondMax}, {"both", BothMin, BothMax},
  } {
    items := []Item{{3, 0}, {1, 1}, {4, 2}, {1, 3}, {4, 4}}
    if got := tc.min(items); got != items[1] { t.Errorf("%s min = %+v", tc.name, got) }
    if got := tc.max(items); got != items[2] { t.Errorf("%s max = %+v", tc.name, got) }
    for _, fn := range []func([]Item) Item{tc.min, tc.max} {
      func() { defer func() { if recover() == nil { t.Errorf("%s did not panic on empty slice", tc.name) } }(); fn(nil) }()
    }
  }
}
`,
	})
	loaded, err := loadpkg.LoadPackage(context.Background(), dir, config.CLIConfig{})
	if err != nil {
		t.Fatal(err)
	}
	plan, err := model.BuildPackage(loaded)
	if err != nil {
		t.Fatal(err)
	}
	generated, err := GeneratePackage(plan)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(generated), "best_ := &s[0]") {
		t.Fatal("generated best pointer did not avoid comparator name collision")
	}
	if err := os.WriteFile(filepath.Join(dir, config.DefaultOutputFilename), generated, 0o644); err != nil {
		t.Fatal(err)
	}
	command := exec.Command("go", "test", "./...")
	command.Dir = dir
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("generated byref min/max test: %v\n%s", err, output)
	}
}

func TestGeneratePackageSortGroupsShareSupportAndCompile(t *testing.T) {
	dir := genPackageFiles(t, map[string]string{
		"records.go": `package fixture

type Item struct{ Key, Seq int }
func byID(left, right Item) int { return left.Key-right.Key }
func byName(left, right Item) int { return right.Key-left.Key }
//monoslices:generate name=Foos cmp=byID ops=sort
//monoslices:generate name=Foos cmp=byName ops=sort-stable
//monoslices:generate name=Bars cmp=byName ops=sort
`,
		"records_test.go": `package fixture
import "testing"
func TestGeneratedSorts(t *testing.T) { v:=[]Item{{Key:2},{Key:1},{Key:2}}; FoosSort(v); if v[0].Key != 1 { t.Fatal(v) }; FoosSortStable(v); w:=[]Item{{Key:1},{Key:3},{Key:2}}; BarsSort(w); if w[0].Key != 3 { t.Fatal(w) } }
`,
	})
	loaded, err := loadpkg.LoadPackage(context.Background(), dir, config.CLIConfig{})
	if err != nil {
		t.Fatal(err)
	}
	plan, err := model.BuildPackage(loaded)
	if err != nil {
		t.Fatal(err)
	}
	generated, err := GeneratePackage(plan)
	if err != nil {
		t.Fatal(err)
	}
	source := string(generated)
	if strings.Count(source, "type monoslices_FoosSort_SortedHint_helper") != 1 || strings.Count(source, "type monoslices_FoosSort_Xorshift_helper") != 1 {
		t.Fatal("unstable support was not shared")
	}
	if strings.Count(source, "func monoslices_FoosSort_InsertionSort_helper") != 1 {
		t.Fatal("sort helper missing")
	}
	if err := os.WriteFile(filepath.Join(dir, config.DefaultOutputFilename), generated, 0o644); err != nil {
		t.Fatal(err)
	}
	command := exec.Command("go", "test", "./...")
	command.Dir = dir
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("generated package sort test: %v\n%s", err, output)
	}
}

func TestGeneratePackageSpecFuncLocalCollisionsCompile(t *testing.T) {
	dir := genPackageFiles(t, map[string]string{
		"specializations.go": `package fixture

type A int
func i(value A) bool { return value > 0 }

type Item struct{ Key int }
func child(left, right Item) int { return left.Key - right.Key }
func k(left, right Item) int { return left.Key - right.Key }

//monoslices:generate name=As pred=i ops=contains
//monoslices:generate name=Unstable cmp=child ops=sort
//monoslices:generate name=Stable cmp=k ops=sort-stable
`,
		"specializations_test.go": `package fixture

import "testing"

func TestGenerated(t *testing.T) {
	if !AsContains([]A{1}) {
		t.Fatal("contains")
	}
	unstable := []Item{{Key: 3}, {Key: 1}, {Key: 2}}
	UnstableSort(unstable)
	stable := []Item{{Key: 2}, {Key: 1}, {Key: 2}}
	StableSortStable(stable)
	if unstable[0].Key != 1 || unstable[1].Key != 2 || unstable[2].Key != 3 || stable[0].Key != 1 || stable[1].Key != 2 || stable[2].Key != 2 {
		t.Fatalf("generated sorts = %#v, %#v", unstable, stable)
	}
}
`,
	})
	loaded, err := loadpkg.LoadPackage(context.Background(), dir, config.CLIConfig{})
	if err != nil {
		t.Fatal(err)
	}
	plan, err := model.BuildPackage(loaded)
	if err != nil {
		t.Fatal(err)
	}
	generated, err := GeneratePackage(plan)
	if err != nil {
		t.Fatal(err)
	}
	source := string(generated)
	for _, want := range []string{
		"for i_ := range s",
		"i(s[i_])",
		"func monoslices_UnstableSort_SiftDown_helper(data []Item, lo, hi, first int)",
		"child(data[first+child_], data[first+child_+1])",
		"func monoslices_StableSortStable_SymMerge_helper(data []Item, a, m, b int)",
		"for k_ := a; k_ < i-1; k_++",
		"k(data[h], data[a])",
	} {
		if !strings.Contains(source, want) {
			t.Errorf("generated source lacks %q:\n%s", want, source)
		}
	}
	if err := os.WriteFile(filepath.Join(dir, config.DefaultOutputFilename), generated, 0o644); err != nil {
		t.Fatal(err)
	}
	command := exec.Command("go", "test", "./...")
	command.Dir = dir
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("generated specialization collision test: %v\n%s", err, output)
	}
}

