type operationTemplateData struct {
	PublicName string
	FuncName   string
	ByrefNote  string
	Elem1      string
	Elem2      string
	Target     string

	Arg1ByRef bool
	Arg2ByRef bool
	UseBest   bool

	Operation        string
	OperationLower   string
	Comparison       string
	Locals           localNames
	SortHelper       string
	StableSortHelper string
	Bits             string
}

var operationTemplateNames = map[config.Operation]string{
	config.OperationContains:     "contains",
	config.OperationIndex:        "index",
	config.OperationDelete:       "delete",
	config.OperationCompact:      "compact",
	config.OperationEqual:        "equal",
	config.OperationCompare:      "compare",
	config.OperationMin:          "min",
	config.OperationMax:          "max",
	config.OperationIsSorted:     "is-sorted",
	config.OperationBinarySearch: "binary-search",
}

var functionTemplates = template.Must(template.New("functions").Funcs(template.FuncMap{
	"local":       operationLocal,
	"at":          operationAt,
	"offset":      operationOffset,
	"call":        operationCall,
	"call2":       operationCall2,
	"bestOperand": operationBestOperand,
}).Parse(functionTemplateText))

func newOperationTemplateData(plan *model.OperationPlan, types renderedTypes) operationTemplateData {
	operation := ""
	operationLower := ""
	comparison := ""
	if plan.Op == config.OperationMin {
		operation, operationLower, comparison = "Min", "min", "< 0"
	} else if plan.Op == config.OperationMax {
		operation, operationLower, comparison = "Max", "max", "> 0"
	}
	return operationTemplateData{
		PublicName:     plan.PublicName,
		FuncName:       plan.Func.Name,
		ByrefNote:      byrefNote(plan),
		Elem1:          types.elem1,
		Elem2:          types.elem2,
		Target:         types.target,
		Arg1ByRef:      plan.Arg1ByRef,
		Arg2ByRef:      plan.Arg2ByRef,
		UseBest:        plan.Arg1ByRef || plan.Arg2ByRef,
		Operation:      operation,
		OperationLower: operationLower,
		Comparison:     comparison,
		Locals:         operationLocalNames(plan),
	}
}

func operationLocal(data operationTemplateData, name string) (string, error) {
	local, ok := data.Locals.names[name]
	if !ok {
		return "", fmt.Errorf("operation template local %q was not allocated", name)
	}
	return local, nil
}

func operationAt(data operationTemplateData, slice, index string) (string, error) {
	local, err := operationLocal(data, slice)
	if err != nil {
		return "", err
	}
	return local + "[" + index + "]", nil
}

func operationOffset(data operationTemplateData, name, suffix string) (string, error) {
	local, err := operationLocal(data, name)
	if err != nil {
		return "", err
	}
	return local + suffix, nil
}

func operationCall(data operationTemplateData, expression string, byref bool) string {
	return call(data.FuncName, expression, byref)
}

func operationCall2(data operationTemplateData, first, second string, firstByRef, secondByRef bool) string {
	return call2(data.FuncName, first, second, firstByRef, secondByRef)
}

func operationBestOperand(data operationTemplateData) string {
	best := data.Locals.Name("best")
	if data.Arg2ByRef {
		return best
	}
	return "*" + best
}

func executeFunctionTemplate(destination *bytes.Buffer, name string, data operationTemplateData) error {
	var generated bytes.Buffer
	if err := functionTemplates.ExecuteTemplate(&generated, name, data); err != nil {
		return fmt.Errorf("monoslices: render function template %q: %w", name, err)
	}
	destination.Write(bytes.TrimSpace(generated.Bytes()))
	destination.WriteByte('\n')
	return nil
}

