// Command casegen writes the concrete benchmark loops for each record mode.
// Keeping the timed calls concrete avoids adding function-value dispatch to
// short operations merely to share benchmark setup code.
package main

import (
	"fmt"
	"go/format"
	"os"
	"strings"
)

type variant struct {
	label, prefix, makeRecord, predicate, equal, compare, searchCompare, sink string
}

var variants = []variant{
	{"record-008-value", "Record008Value", "makeRecord008", "record008Predicate", "record008Equal", "record008Compare", "record008SearchCompare", "benchmark008Sink"},
	{"record-016-value", "Record016Value", "makeRecord016", "record016Predicate", "record016Equal", "record016Compare", "record016SearchCompare", "benchmark016Sink"},
	{"record-016-byref", "Record016Byref", "makeRecord016", "record016Predicate", "record016Equal", "record016Compare", "record016SearchCompare", "benchmark016Sink"},
	{"record-064-byref", "Record064Byref", "makeRecord064", "record064PredicateValue", "record064EqualValue", "record064CompareValue", "record064SearchCompare", "benchmark064Sink"},
	{"record-256-byref", "Record256Byref", "makeRecord256", "record256PredicateValue", "record256EqualValue", "record256CompareValue", "record256SearchCompare", "benchmark256Sink"},
}

func main() {
	var out strings.Builder
	fmt.Fprintln(&out, "// Code generated by internal/benchmarks/internal/casegen. DO NOT EDIT.\npackage benchmarks\n\nimport (\"fmt\"; \"slices\"; \"testing\")")
	for _, op := range []string{"Index", "Contains", "Equal", "Compare", "Min", "Max", "IsSorted", "BinarySearch", "Delete", "Compact", "Sort", "SortStable"} {
		size := "benchmarkSliceSize"
		if op == "Sort" || op == "SortStable" {
			size = "benchmarkSortSize"
		}
		fmt.Fprintf(&out, "\nfunc Benchmark%s(b *testing.B) {\n\tconst n = %s\n", op, size)
		for _, v := range variants {
			writeVariant(&out, op, v)
		}
		fmt.Fprintln(&out, "}")
	}
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("cases_generated_test.go", formatted, 0o644); err != nil {
		panic(err)
	}
}

func writeVariant(out *strings.Builder, op string, v variant) {
	// Each block scopes its fixture variables. Only input distributions that
	// actually vary use loops; the timed calls remain direct in b.Loop.
	fmt.Fprintln(out, "\t{")
	switch op {
	case "Index", "Contains":
		fmt.Fprintf(out, "\t\tvalues := recordScanCase(n, -1, %s)\n", v.makeRecord)
		fmt.Fprintf(out, "\t\trunImplementations(b, fmt.Sprintf(%q, n),\n", v.label+"/size-%d/miss")
		sink, call := "benchmarkIntSink", "IndexFunc"
		if op == "Contains" {
			sink, call = "benchmarkBoolSink", "ContainsFunc"
		}
		writePair(out, "", fmt.Sprintf("%s = %s%s(values)", sink, v.prefix, op), fmt.Sprintf("%s = slices.%s(values, %s)", sink, call, v.predicate))
	case "Equal", "Compare":
		fmt.Fprintf(out, "\t\tvalues := recordEqualCase(n, -1, %s)\n", v.makeRecord)
		fmt.Fprintf(out, "\t\trunImplementations(b, fmt.Sprintf(%q, n),\n", v.label+"/size-%d/equal")
		sink, call, cb := "benchmarkIntSink", "CompareFunc", v.compare
		if op == "Equal" {
			sink, call, cb = "benchmarkBoolSink", "EqualFunc", v.equal
		}
		writePair(out, "", fmt.Sprintf("%s = %s%s(values.left, values.right)", sink, v.prefix, op), fmt.Sprintf("%s = slices.%s(values.left, values.right, %s)", sink, call, cb))
	case "Min", "Max":
		fmt.Fprintf(out, "\t\tvalues := recordPattern(n, patternRandom, %s)\n", v.makeRecord)
		fmt.Fprintf(out, "\t\trunImplementations(b, fmt.Sprintf(%q, n),\n", v.label+"/size-%d")
		writePair(out, "", fmt.Sprintf("%s = %s%s(values)", v.sink, v.prefix, op), fmt.Sprintf("%s = slices.%sFunc(values, %s)", v.sink, op, v.compare))
	case "IsSorted":
		fmt.Fprintf(out, "\t\tvalues := recordPattern(n, patternSorted, %s)\n", v.makeRecord)
		fmt.Fprintf(out, "\t\trunImplementations(b, fmt.Sprintf(%q, n),\n", v.label+"/size-%d/sorted")
		writePair(out, "", fmt.Sprintf("benchmarkBoolSink = %sIsSorted(values)", v.prefix), fmt.Sprintf("benchmarkBoolSink = slices.IsSortedFunc(values, %s)", v.compare))
	case "BinarySearch":
		fmt.Fprint(out, "\t\tfor _, input := range searchInputs {\n")
		fmt.Fprintf(out, "\t\t\tvalues := recordSearch(n, %s)\n\t\t\ttarget := SearchKey{Key: searchTarget(n, input.kind)}\n", v.makeRecord)
		fmt.Fprintf(out, "\t\t\trunImplementations(b, fmt.Sprintf(%q, n, input.name),\n", v.label+"-record-key/size-%d/%s")
		writePair(out, "", fmt.Sprintf("benchmarkIntSink, benchmarkBoolSink = %sSearchBinarySearch(values, target)", v.prefix), fmt.Sprintf("benchmarkIntSink, benchmarkBoolSink = slices.BinarySearchFunc(values, target, %s)", v.searchCompare))
		fmt.Fprint(out, "\t\t}\n")
		fmt.Fprintf(out, "\t\tvalues := recordSearch(n, %s)\n\t\tqueries := variedSearchTargets(n)\n", v.makeRecord)
		fmt.Fprintf(out, "\t\trunImplementations(b, fmt.Sprintf(%q, n),\n", v.label+"-record-key/size-%d/varied")
		generated := fmt.Sprintf("for i := range queries { benchmarkIntSink, benchmarkBoolSink = %sSearchBinarySearch(values, queries[i]) }", v.prefix)
		standard := fmt.Sprintf("for i := range queries { benchmarkIntSink, benchmarkBoolSink = slices.BinarySearchFunc(values, queries[i], %s) }", v.searchCompare)
		writePair(out, "reportQueryTime(b, len(queries))", generated, standard)
	case "Delete", "Compact":
		if op == "Delete" {
			fmt.Fprint(out, "\t\tfor _, input := range benchmarkDeleteDensities {\n")
			fmt.Fprintf(out, "\t\t\tsource := recordDeleteCase(n, input, %s)\n", v.makeRecord)
		} else {
			fmt.Fprint(out, "\t\tfor _, input := range compactPatterns {\n")
			fmt.Fprintf(out, "\t\t\tsource := recordCompact(n, input.spacing, %s)\n", v.makeRecord)
		}
		fmt.Fprintf(out, "\t\t\tname := fmt.Sprintf(%q, n, input.name)\n", v.label+"/size-%d/%s")
		noChange := "input.none"
		cb := v.predicate
		if op == "Compact" {
			noChange, cb = "input.spacing == 0", v.equal
		}
		fmt.Fprintf(out, "\t\t\tif %s {\n\t\t\t\trunImplementations(b, name,\n", noChange)
		writePair(out, "", fmt.Sprintf("benchmarkLenSink = len(%s%s(source))", v.prefix, op), fmt.Sprintf("benchmarkLenSink = len(slices.%sFunc(source, %s))", op, cb))
		fmt.Fprint(out, "\t\t\t\tcontinue\n\t\t\t}\n\t\t\twork := slices.Clone(source)\n\t\t\trunImplementations(b, name,\n")
		setup := "b.StopTimer(); copy(work, source); b.StartTimer()"
		writePair(out, "", setup+fmt.Sprintf("; benchmarkLenSink = len(%s%s(work))", v.prefix, op), setup+fmt.Sprintf("; benchmarkLenSink = len(slices.%sFunc(work, %s))", op, cb))
		fmt.Fprint(out, "\t\t}\n")
	case "Sort", "SortStable":
		fmt.Fprint(out, "\t\tfor _, input := range benchmarkSortPatterns {\n")
		fmt.Fprintf(out, "\t\t\tsource := recordPattern(n, input.pattern, %s)\n", v.makeRecord)
		fmt.Fprintf(out, "\t\t\tname := fmt.Sprintf(%q, input.name, n)\n", v.label+"/%s/size-%d")
		fmt.Fprint(out, "\t\t\tif input.pattern == patternSorted {\n\t\t\t\trunImplementations(b, name,\n")
		writePair(out, "", fmt.Sprintf("%s%s(source)", v.prefix, op), fmt.Sprintf("slices.%sFunc(source, %s)", op, v.compare))
		fmt.Fprint(out, "\t\t\t\tcontinue\n\t\t\t}\n\t\t\twork := slices.Clone(source)\n\t\t\trunImplementations(b, name,\n")
		setup := "b.StopTimer(); copy(work, source); b.StartTimer()"
		writePair(out, "", setup+fmt.Sprintf("; %s%s(work)", v.prefix, op), setup+fmt.Sprintf("; slices.%sFunc(work, %s)", op, v.compare))
		fmt.Fprint(out, "\t\t}\n")
	}
	fmt.Fprintln(out, "\t}")
}

func writePair(out *strings.Builder, after, generated, standard string) {
	for _, body := range []string{generated, standard} {
		fmt.Fprintf(out, "\t\tfunc(b *testing.B) { b.ReportAllocs(); for b.Loop() { %s }; %s },\n", body, after)
	}
	fmt.Fprint(out, "\t\t)\n")
}
