func TestLoadPackageDiscoversDirectivesInDeterministicOrder(t *testing.T) {
	dir := packageDir(t, map[string]string{
		"z_records.go": `package sample
// monoslices:generate name=Ignored cmp=compare
//monoslices:generate name=Zulu cmp=compare
`,
		"a_records.go": `package sample

type A int
func compare(a, b A) int { return int(a-b) }
//monoslices:generate name=Alpha cmp=compare
//monoslices:generateX name=Ignored cmp=compare
`,
		"monoslices_gen.go": `// Code generated by monoslices. DO NOT EDIT.
package stale
func stale() {}
`,
	})
	loaded, err := LoadPackage(context.Background(), dir, config.CLIConfig{})
	if err != nil {
		t.Fatalf("LoadPackage() error = %v", err)
	}
	if got, want := loaded.OutputPath, filepath.Join(dir, config.DefaultOutputFilename); got != want {
		t.Fatalf("OutputPath = %q, want %q", got, want)
	}
	if len(loaded.Directives) != 2 || loaded.Directives[0].Config.Name != "Alpha" || loaded.Directives[1].Config.Name != "Zulu" {
		t.Fatalf("directives = %#v", loaded.Directives)
	}
	if len(loaded.OwnedFiles) != 1 || filepath.Base(loaded.OwnedFiles[0]) != "monoslices_gen.go" {
		t.Fatalf("owned files = %#v, want monoslices_gen.go", loaded.OwnedFiles)
	}
	for _, file := range loaded.SourceFiles {
		if file.Filename == "monoslices_gen.go" {
			t.Fatal("owned output was included in handwritten source inventory")
		}
	}
}

func TestLoadPackageAllowsSyntacticallyValidTypeErrors(t *testing.T) {
	tests := []struct {
		name          string
		extraSource   string
		function      string
		parameterType string
		operations    string
	}{
		{
			name:          "undefined identifier in ordinary body",
			extraSource:   "func broken() { missing() }",
			function:      "broken",
			parameterType: "Item",
			operations:    "compare",
		},
		{
			name:          "invalid specialization body",
			extraSource:   "func compare(a, b Item) int { return unresolved(a, b) }",
			function:      "compare",
			parameterType: "Item",
			operations:    "compare",
		},
		{
			name:          "missing generated public operation",
			extraSource:   "func useItems(items []Item) { ItemsSort(items) }",
			function:      "useItems",
			parameterType: "Item",
			operations:    "sort",
		},
		{
			name:          "unresolved local specialization type",
			extraSource:   "func compare(a, b Missing) int { return 0 }",
			function:      "compare",
			parameterType: "Missing",
			operations:    "compare",
		},
		{
			name:          "invalid declaration",
			extraSource:   "var invalid int = \"not an int\"",
			function:      "compare",
			parameterType: "Item",
			operations:    "compare",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			source := "package sample\n\ntype Item int\n" + test.extraSource + "\n"
			if !strings.Contains(test.extraSource, "func compare") {
				source += "func compare(a, b Item) int { return 0 }\n"
			}
			source += "//monoslices:generate name=Items cmp=compare ops=" + test.operations + "\n"
			dir := packageDir(t, map[string]string{"records.go": source})
			loaded, err := LoadPackage(context.Background(), dir, config.CLIConfig{})
			if err != nil {
				t.Fatalf("LoadPackage() error = %v", err)
			}
			if len(loaded.Directives) != 1 || loaded.Directives[0].Config.Name != "Items" {
				t.Fatalf("directives = %#v, want Items directive", loaded.Directives)
			}
			var target, compare *SourceFuncDecl
			for fileIndex := range loaded.SourceFiles {
				file := &loaded.SourceFiles[fileIndex]
				if file.Filename != "records.go" {
					continue
				}
				for functionIndex := range file.Functions {
					function := &file.Functions[functionIndex]
					if function.Name == test.function {
						target = function
					}
					if function.Name == "compare" {
						compare = function
					}
				}
			}
			if target == nil || target.Decl == nil {
				t.Fatalf("source function %q was not discovered", test.function)
			}
			if compare == nil || compare.Decl == nil {
				t.Fatal("specialization source function compare was not discovered")
			}
			params := compare.Decl.Type.Params
			if params == nil || len(params.List) != 1 || len(params.List[0].Names) != 2 {
				t.Fatalf("source parameters = %#v, want grouped pair", params)
			}
			typeName, ok := params.List[0].Type.(*ast.Ident)
			if !ok || typeName.Name != test.parameterType {
				t.Fatalf("source parameter type = %#v, want %s", params.List[0].Type, test.parameterType)
			}
		})
	}
}

