func includedSourceDeclarations(pkg *Package) []SourceDeclaration {
	var declarations []SourceDeclaration
	for _, file := range pkg.SourceFiles {
		if file.ExternalTest {
			continue
		}
		declarations = append(declarations, file.Declarations...)
	}
	return declarations
}

func includedSourceImports(pkg *Package) []SourceImport {
	var imports []SourceImport
	for _, file := range pkg.SourceFiles {
		if file.ExternalTest {
			continue
		}
		imports = append(imports, file.Imports...)
	}
	return imports
}

func TestHasExplicitBuildConstraintUsesHeaderPlacement(t *testing.T) {
	cases := []struct {
		name string
		data string
		want bool
	}{
		{
			name: "go build header",
			data: "//go:build linux\n\npackage sample\n",
			want: true,
		},
		{
			name: "BOM-prefixed go build header",
			data: "\ufeff//go:build linux\n\npackage sample\n",
			want: true,
		},
		{
			name: "BOM-prefixed legacy header",
			data: "\ufeff// +build linux\n\npackage sample\n",
			want: true,
		},
		{
			name: "legacy header",
			data: "// +build linux\n\npackage sample\n",
			want: true,
		},
		{
			name: "legacy without header separator",
			data: "// +build linux\npackage sample\n",
			want: false,
		},
		{
			name: "legacy after package",
			data: "package sample\n\n// +build linux\n",
			want: false,
		},
		{
			name: "legacy in block comment",
			data: "/*\n// +build linux\n*/\n\npackage sample\n",
			want: false,
		},
		{
			name: "go build in block comment",
			data: "/* //go:build linux */\n\npackage sample\n",
			want: false,
		},
	}
	for _, test := range cases {
		t.Run(test.name, func(t *testing.T) {
			if got := hasExplicitBuildConstraint([]byte(test.data)); got != test.want {
				t.Fatalf("hasExplicitBuildConstraint() = %v, want %v", got, test.want)
			}
		})
	}
}

