func TestLoadPackageRetainsConstraintProvenanceWithoutSolving(t *testing.T) {
	dir := packageDir(t, map[string]string{
		"records.go": `package sample

type Item int
func compare(left, right Item) int { return int(left - right) }
//monoslices:generate name=Items cmp=compare ops=compare
`,
		"custom_linux.go": `//go:build custom

package sample
`,
		"release_windows.go": `//go:build go1.25

package sample
`,
		"legacy.go": `// +build custom

package sample
`,
		"cgo.go": `//go:build phase7cgo

package sample

import "C"
`,
		"records_nacl.go": "package sample\n",
	})
	loaded, err := LoadPackage(context.Background(), dir, config.CLIConfig{})
	if err != nil {
		t.Fatalf("LoadPackage() error = %v", err)
	}
	want := map[string]struct {
		expression string
		cgo        bool
	}{
		"custom_linux.go":    {expression: "custom"},
		"release_windows.go": {expression: "go1.25"},
		"legacy.go":          {expression: "custom"},
		"cgo.go":             {expression: "phase7cgo", cgo: true},
		"records_nacl.go":    {},
	}
	seen := make(map[string]bool, len(want))
	for _, file := range loaded.SourceFiles {
		check, ok := want[file.Filename]
		if !ok {
			continue
		}
		seen[file.Filename] = true
		if !file.Constraint.Constrained || file.Constraint.GoBuildExpression != check.expression ||
			file.Constraint.RequiresCgo != check.cgo {
			t.Errorf("%s constraint = %#v, want expression %q cgo %v", file.Filename, file.Constraint, check.expression, check.cgo)
		}
	}
	for name := range want {
		if !seen[name] {
			t.Errorf("source inventory lacks %s", name)
		}
	}
}

func TestLoadPackageAcceptsUnresolvedInactiveDefaultImport(t *testing.T) {
	dir := packageDir(t, map[string]string{
		"records.go": `package sample

type Item int
func compare(left, right Item) int { return int(left - right) }
//monoslices:generate name=Items cmp=compare ops=compare
`,
		"records_windows.go": `//go:build windows

package sample

import "example.com/sample/missing"
var _ = missing.Value
`,
	})
	loaded, err := LoadPackage(context.Background(), dir, config.CLIConfig{})
	if err != nil {
		t.Fatalf("LoadPackage() error = %v, want unavailable default import to remain unresolved", err)
	}
	for _, imported := range includedSourceImports(loaded) {
		if imported.Filename != "records_windows.go" || imported.ImportPath != "example.com/sample/missing" {
			continue
		}
		if imported.Name != "" || imported.ExplicitAlias || !imported.Constrained {
			t.Fatalf("inactive default import = %#v, want unresolved name with constraint provenance", imported)
		}
		return
	}
	t.Fatalf("source imports = %#v, want inactive missing import provenance", includedSourceImports(loaded))
}

func packageDir(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/sample\n\ngo 1.24.0\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	for name, content := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}
