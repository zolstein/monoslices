func TestLoadPackageExposesUnifiedSourceInventory(t *testing.T) {
	dir := packageDir(t, map[string]string{
		"records.go": `package sample

type Item int
func compare(left, right Item) int { return int(left - right) }
//monoslices:generate name=Items cmp=compare ops=sort
`,
		"records_windows.go": `//go:build windows

package sample

const InactiveVariant = 1
func variantCmp(a, b Item) int { return int(a - b) }
`,
		"records_test.go": `package sample

const SamePackageTest = 1
`,
		"external_test.go": `package sample_test

const ExternalTest = 1
`,
		"monoslices_gen.go": "package stale\nconst StaleOutput = 1\n",
	})
	loaded, err := LoadPackage(context.Background(), dir, config.CLIConfig{})
	if err != nil {
		t.Fatalf("LoadPackage() error = %v", err)
	}
	if loaded.Name != "sample" {
		t.Fatalf("package name = %q, want sample", loaded.Name)
	}
	if loaded.SourceFset == nil || len(loaded.SourceFiles) != 4 {
		t.Fatalf("source inventory = fset %v, %d files; want one fset and four files", loaded.SourceFset != nil, len(loaded.SourceFiles))
	}
	var foundInactive, foundVariantFunction, foundSame, foundExternal bool
	for _, file := range loaded.SourceFiles {
		switch file.Filename {
		case "records_windows.go":
			if !file.Constraint.Constrained || file.Constraint.GoBuildExpression != "windows" {
				t.Fatalf("windows source constraint = %#v", file.Constraint)
			}
			for _, declaration := range file.Declarations {
				if declaration.Name == "InactiveVariant" {
					foundInactive = true
				}
			}
			for _, function := range file.Functions {
				if function.Name == "variantCmp" {
					if !function.Constrained {
						t.Fatalf("constrained source function = %#v", function)
					}
					foundVariantFunction = true
				}
			}
		case "records_test.go":
			if !file.Test || file.ExternalTest {
				t.Fatalf("same-package test classification = test %v external %v", file.Test, file.ExternalTest)
			}
			for _, declaration := range file.Declarations {
				if declaration.Name == "SamePackageTest" {
					foundSame = true
				}
			}
		case "external_test.go":
			if !file.Test || !file.ExternalTest {
				t.Fatalf("external test classification = test %v external %v", file.Test, file.ExternalTest)
			}
			for _, declaration := range file.Declarations {
				if declaration.Name == "ExternalTest" {
					foundExternal = true
				}
			}
		}
	}
	for _, declaration := range includedSourceDeclarations(loaded) {
		if declaration.Name == "InactiveVariant" {
			foundInactive = true
		}
	}
	if !foundInactive || !foundVariantFunction || !foundSame || !foundExternal {
		t.Fatalf("source inventory: inactive=%v variant function=%v same=%v external=%v", foundInactive, foundVariantFunction, foundSame, foundExternal)
	}
}

