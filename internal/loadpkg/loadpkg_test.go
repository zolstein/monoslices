// Release-version context supplements a parse failure; it does not preempt parsing.
func TestSourceParseErrorVersionContext(t *testing.T) {
	const parserError = "syntax error from parser"
	tests := []struct {
		name          string
		source        string
		parserVersion string
		wantContext   bool
		wantVersions  []string
	}{
		{
			name: "newer requirement",
			source: `//go:build go1.28

package sample
`,
			parserVersion: "go1.27",
			wantContext:   true,
			wantVersions:  []string{"Go 1.28", "Go 1.27"},
		},
		{
			name: "equal requirement",
			source: `//go:build go1.28

package sample
`,
			parserVersion: "go1.28",
		},
		{
			name: "older requirement",
			source: `//go:build go1.26

package sample
`,
			parserVersion: "go1.27",
		},
		{
			name: "constraint without minimum version",
			source: `//go:build linux && custom

package sample
`,
			parserVersion: "go1.27",
		},
		{
			name: "negated release constraint",
			source: `//go:build !go1.28

package sample
`,
			parserVersion: "go1.27",
		},
		{
			name: "malformed constraint",
			source: `//go:build go1.28 &&

package sample
`,
			parserVersion: "go1.27",
		},
		{
			name: "multiple modern constraints",
			source: `//go:build go1.28
//go:build go1.29

package sample
`,
			parserVersion: "go1.27",
		},
		{
			name: "unavailable parser version",
			source: `//go:build go1.28

package sample
`,
			parserVersion: "",
		},
		{
			name: "multiple legacy constraints use AND semantics",
			source: `// +build go1.28
// +build go1.27

package sample
`,
			parserVersion: "go1.27",
			wantContext:   true,
			wantVersions:  []string{"Go 1.28", "Go 1.27"},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			err := sourceParseError("future.go", []byte(test.source), errors.New(parserError), test.parserVersion)
			message := err.Error()
			if !strings.Contains(message, parserError) {
				t.Fatalf("diagnostic %q does not preserve parser error", message)
			}
			gotContext := strings.Contains(message, "file build constraints require Go")
			if gotContext != test.wantContext {
				t.Fatalf("diagnostic = %q, contextual version message present %v; want %v", message, gotContext, test.wantContext)
			}
			for _, version := range test.wantVersions {
				if !strings.Contains(message, version) {
					t.Errorf("diagnostic %q does not contain %q", message, version)
				}
			}
		})
	}
}

